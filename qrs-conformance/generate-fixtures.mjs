/**
 * Golden-vector fixture generator for the qrs-core conformance suite.
 *
 * Produces a language-neutral JSON fixture (`fixtures/golden.json`) that both the
 * TypeScript and Python test suites consume. Every vector is deterministic:
 *   - canonical CBOR encodings (byte-identical across languages);
 *   - key_id / tcert_id / sdoc_id derivations from FIXED keys;
 *   - canonical public-key bytes.
 *
 * Signed-object *signature bytes* are intentionally NOT golden vectors: ECDSA
 * signatures are non-deterministic (random k). Cross-language signature
 * compatibility is instead proven by the bidirectional verify tests
 * (JS signs → Python verifies, and vice versa).
 *
 * Run:  node generate-fixtures.mjs
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { cborEncode } from '../qrs-core-js/dist/cbor/canonical.js';
import { toHex, truncSha256, sha256, sha384, sha3_512, hashFor } from '../qrs-core-js/dist/id.js';
import { canonicalPublicKeyBytes } from '../qrs-core-js/dist/crypto/jwk.js';
import { computeKeyId } from '../qrs-core-js/dist/crypto/providers.js';
import { Ed25519Provider } from '../qrs-core-js/dist/crypto/ed25519.js';
import { EcdsaP256Provider } from '../qrs-core-js/dist/crypto/ecdsaP256.js';
import { tcertIdOf, sdocIdOf } from '../qrs-core-js/dist/signedObject/signedObject.js';
import { encodeTransferPayload, encodeBundle, encodeQrsFile, encodeQrsBundleFile } from '../qrs-core-js/dist/transfer.js';

const __dirname = dirname(fileURLToPath(import.meta.url));

// Fixed private seed (0..31) → deterministic public keys in BOTH languages.
const SEED = Uint8Array.from({ length: 32 }, (_, i) => i);
const seedB64 = Buffer.from(SEED).toString('base64url');

// Build fixed JWKs. Ed25519: x derived from seed. ECDSA: x/y derived from seed.
const edProvider = new Ed25519Provider();
const edPair = await edProvider.generateKeyPair();
// Override with deterministic key derived from the seed.
const edPriv = { kty: 'OKP', crv: 'Ed25519', x: 'A6EHv_POEL4dcN0Y50vAmWfk1jCbpQ1fHdyGZBJVMbg', d: seedB64 };
const edPub = await edProvider.derivePublic(edPriv);

const ecProvider = new EcdsaP256Provider();
const ecPub = {
  kty: 'EC',
  crv: 'P-256',
  x: 'elkxgIYMQDfIPBJ0mEXI7hQk3Sl_rcuJXjWCVdLH0rI',
  y: 'qMolWA8mJv5XkGL_G5n_kcJKDaBvsytb4gFIySSfVlA',
};
const ecPriv = { ...ecPub, d: seedB64 };

const hex = (u8) => toHex(u8);

// ---- CBOR battery ----
const cborCases = {
  null: cborEncode(null),
  true: cborEncode(true),
  false: cborEncode(false),
  zero: cborEncode(0),
  one: cborEncode(1),
  negOne: cborEncode(-1),
  int23: cborEncode(23),
  int24: cborEncode(24),
  int255: cborEncode(255),
  int256: cborEncode(256),
  int65535: cborEncode(65535),
  int65536: cborEncode(65536),
  intMax32: cborEncode(0xffffffff),
  intMax64: cborEncode(0xffffffffffffffffn),
  neg100: cborEncode(-100),
  negMax64: cborEncode(-(2n ** 63n)),
  text: cborEncode('hello'),
  textUnicode: cborEncode('héllo 世界'),
  bytes: cborEncode(Uint8Array.from([0, 1, 2, 255])),
  array: cborEncode([1, 'two', [3, 4], null]),
  mapSorted: cborEncode({ b: 1, a: 2, c: { z: 0, y: 1 } }),
  mapIntKeys: cborEncode(new Map([[1, 'one'], [2, 'two']])),
  nested: cborEncode({ a: [1, { b: 'x' }], c: Uint8Array.from([9, 8]) }),
};

// ---- Hashing ----
const hashCases = {
  sha256: hex(sha256(new TextEncoder().encode('qrs'))),
  sha384: hex(sha384(new TextEncoder().encode('qrs'))),
  sha3_512: hex(sha3_512(new TextEncoder().encode('qrs'))),
  hashForDefault: hex(hashFor(undefined, new TextEncoder().encode('qrs'))),
  hashForSha384: hex(hashFor('SHA-384', new TextEncoder().encode('qrs'))),
  truncSha256: hex(truncSha256(new TextEncoder().encode('qrs'))),
};

// ---- Key derivation ----
const keyCases = {
  ed25519: {
    publicJwk: edPub,
    canonicalPublicKey: hex(canonicalPublicKeyBytes(edPub)),
    keyId: edProvider.keyId(edPub),
  },
  ecdsaP256: {
    publicJwk: ecPub,
    canonicalPublicKey: hex(canonicalPublicKeyBytes(ecPub)),
    keyId: ecProvider.keyId(ecPub),
  },
};

// ---- Identifier derivation ----
const idCases = {
  tcertIdEd: tcertIdOf(edProvider.keyId(edPub), 1),
  tcertIdEc: tcertIdOf(ecProvider.keyId(ecPub), 7),
  sdocId: sdocIdOf(Uint8Array.from([1, 2, 3, 4])),
};

// ---- Transfer envelope (deterministic strings) ----
const transferCases = {
  payload: encodeTransferPayload('sdoc', 'aGVsbG8'),
  bundle: encodeBundle([
    { type: 'tcert', bytesB64: 'dGNlcnQ' },
    { type: 'sdoc', bytesB64: 'c2RvYw' },
  ]),
  qrsFile: hex(encodeQrsFile('tcert', 'dGNlcnQ')),
  qrsBundleFile: hex(encodeQrsBundleFile([{ type: 'statement', bytesB64: 'c3RhdGU' }])),
};

const fixture = {
  _comment:
    'Golden vectors for qrs-core conformance. Generated by src/qrs-conformance/generate-fixtures.mjs. Do not edit by hand.',
  seedB64,
  cbor: Object.fromEntries(Object.entries(cborCases).map(([k, v]) => [k, hex(v)])),
  hashes: hashCases,
  keys: keyCases,
  ids: idCases,
  transfer: transferCases,
};

const outPath = join(__dirname, 'fixtures', 'golden.json');
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, JSON.stringify(fixture, null, 2) + '\n');
console.log('Wrote', outPath);