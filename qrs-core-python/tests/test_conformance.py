def test_hash_vectors_match(golden):
    data = b"qrs"
    assert to_hex(sha256(data)) == golden["hashes"]["sha256"]
    assert to_hex(sha384(data)) == golden["hashes"]["sha384"]
    assert to_hex(sha3_512(data)) == golden["hashes"]["sha3_512"]
    assert to_hex(hash_for(None, data)) == golden["hashes"]["hashForDefault"]
    assert to_hex(hash_for("SHA-384", data)) == golden["hashes"]["hashForSha384"]
    assert to_hex(trunc_sha256(data)) == golden["hashes"]["truncSha256"]


