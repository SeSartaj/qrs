def test_ed25519_key_derivation_matches(golden):
    provider = Ed25519Provider()
    public_jwk = golden["keys"]["ed25519"]["publicJwk"]
    assert to_hex(canonical_public_key_bytes(public_jwk)) == golden["keys"]["ed25519"]["canonicalPublicKey"]
    assert provider.key_id(public_jwk) == golden["keys"]["ed25519"]["keyId"]
    assert compute_key_id(provider, public_jwk) == golden["keys"]["ed25519"]["keyId"]


def test_ecdsa_key_derivation_matches(golden):
    provider = EcdsaP256Provider()
    public_jwk = golden["keys"]["ecdsaP256"]["publicJwk"]
    assert to_hex(canonical_public_key_bytes(public_jwk)) == golden["keys"]["ecdsaP256"]["canonicalPublicKey"]
    assert provider.key_id(public_jwk) == golden["keys"]["ecdsaP256"]["keyId"]


