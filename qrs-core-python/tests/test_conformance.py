"""Cross-implementation conformance tests.

These tests prove the Python ``qrs`` core is *wire-compatible* with the reference
TypeScript ``qrs-core`` implementation. They consume the shared golden-vector
fixture (``src/qrs-conformance/fixtures/golden.json``) and assert that the Python
implementation produces byte-identical output for identical inputs.

The fixture is generated by ``src/qrs-conformance/generate-fixtures.mjs`` (the
TypeScript reference). Regenerate it after any wire-format change:

    node src/qrs-conformance/generate-fixtures.mjs

Run these tests with the rest of the suite:

    PYTHONPATH=src pytest tests/test_conformance.py
"""

