def test_cbor_vectors_match(golden):
    """Python canonical CBOR must byte-match the reference for every vector."""
    cases = {
        "null": None,
        "true": True,
        "false": False,
        "zero": 0,
        "one": 1,
        "negOne": -1,
        "int23": 23,
        "int24": 24,
        "int255": 255,
        "int256": 256,
        "int65535": 65535,
        "int65536": 65536,
        "intMax32": 0xFFFFFFFF,
        "intMax64": 0xFFFFFFFFFFFFFFFF,
        "neg100": -100,
        "negMax64": -(2**63),
        "text": "hello",
        "textUnicode": "héllo 世界",
        "bytes": bytes([0, 1, 2, 255]),
        "array": [1, "two", [3, 4], None],
        "mapSorted": {"b": 1, "a": 2, "c": {"z": 0, "y": 1}},
        "mapIntKeys": {1: "one", 2: "two"},
        "nested": {"a": [1, {"b": "x"}], "c": bytes([9, 8])},
    }
    for name, value in cases.items():
        assert to_hex(cbor_encode(value)) == golden["cbor"][name], f"cbor vector {name}"


