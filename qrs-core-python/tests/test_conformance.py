def test_identifier_vectors_match(golden):
    ed_key_id = golden["keys"]["ed25519"]["keyId"]
    ec_key_id = golden["keys"]["ecdsaP256"]["keyId"]
    assert tcert_id_of(ed_key_id, 1) == golden["ids"]["tcertIdEd"]
    assert tcert_id_of(ec_key_id, 7) == golden["ids"]["tcertIdEc"]
    assert sdoc_id_of(bytes([1, 2, 3, 4])) == golden["ids"]["sdocId"]


