# Bidirectional cross-verification (Python signs → JS verifies, and vice versa)
# --------------------------------------------------------------------------- #

import asyncio  # noqa: E402
import base64  # noqa: E402
import subprocess  # noqa: E402
import sys  # noqa: E402

from qrs.context import DummyContextProvider  # noqa: E402
from qrs.fields import FieldSchema  # noqa: E402
from qrs.runtime import QrsDependencies, create_qrs  # noqa: E402
from qrs.services.certificateService import CreateTcertParams  # noqa: E402
from qrs.services.signingService import IssueSdocParams  # noqa: E402

CONFORMANCE_DIR = Path(__file__).resolve().parents[2] / "qrs-conformance"
JS_VERIFIER = CONFORMANCE_DIR / "verify_js.mjs"
JS_CORE_DIR = Path(__file__).resolve().parents[2] / "qrs-core-js"


def _b64(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode("ascii")


def _verify_in_js(request: dict) -> dict:
    """Run the JS verifier bridge with a JSON request; return the parsed verdict."""
    result = subprocess.run(
        ["node", str(JS_VERIFIER)],
        input=json.dumps(request),
        capture_output=True,
        text=True,
        cwd=str(CONFORMANCE_DIR),
    )
    assert result.returncode == 0, f"node verifier failed: {result.stderr}"
    return json.loads(result.stdout)


async def _make_pair(algorithm: str) -> tuple[bytes, bytes, dict]:
    """Create a TCert + SDoc in Python; return (tcert_bytes, sdoc_bytes, public_jwk)."""
    qrs = create_qrs(
        QrsDependencies(context_provider=DummyContextProvider(secrets={"pin": "s3cret"}))
    )
    tcert = await qrs.certificates.create_tcert(
        CreateTcertParams(
            algorithm=algorithm,
            name="AFDA",
            fields=[
                FieldSchema(type="text", name="license_no", label="License"),
                FieldSchema(type="secretInput", name="pin", label="PIN"),
            ],
        )
    )
    await qrs.trust.pin(tcert.tcert_id)
    issued = await qrs.signing.issue_sdoc(
        IssueSdocParams(
            tcert_id=tcert.tcert_id,
            values={"license_no": "AFDA-123", "pin": "s3cret"},
        )
    )
    from qrs.envelope import parse_signed_object

    public_jwk = parse_signed_object(tcert.bytes).data["publicKey"]
    return tcert.bytes, issued.bytes, public_jwk


@pytest.mark.parametrize("algorithm", ["Ed25519", "ECDSA-P256"])
def test_python_signed_objects_verify_in_js(algorithm):
    """Objects signed by the Python core must verify in the reference JS core."""
    tcert_bytes, sdoc_bytes, public_jwk = asyncio.run(_make_pair(algorithm))

    tcert_verdict = _verify_in_js({"bytesB64": _b64(tcert_bytes), "type": "tcert"})
    assert tcert_verdict["ok"] is True
    assert tcert_verdict["verified"] is True
    assert tcert_verdict["type"] == "tcert"

    sdoc_verdict = _verify_in_js(
        {
            "bytesB64": _b64(sdoc_bytes),
            "type": "sdoc",
            "publicKey": public_jwk,
            "secret": {"pin": "s3cret"},
        }
    )
    assert sdoc_verdict["ok"] is True
    assert sdoc_verdict["verified"] is True
    assert sdoc_verdict["type"] == "sdoc"


@pytest.mark.parametrize("algorithm", ["Ed25519", "ECDSA-P256"])
def test_js_signed_objects_verify_in_python(algorithm):
    """Objects signed by the reference JS core must verify in the Python core."""
    # Produce a JS-signed TCert + SDoc via the JS core, then verify in Python.
    script = f"""
import {{ createQrs }} from '{JS_CORE_DIR}/dist/runtime.js';
import {{ DummyContextProvider }} from '{JS_CORE_DIR}/dist/context/dummyContext.js';
import {{ parseSignedObject }} from '{JS_CORE_DIR}/dist/signedObject/signedObject.js';
import {{ toBase64Url }} from '{JS_CORE_DIR}/dist/id.js';
const rt = createQrs({{ contextProvider: new DummyContextProvider({{ secrets: {{ pin: 's3cret' }} }}) }});
const tcert = await rt.certificates.createTcert({{ algorithm: '{algorithm}', name: 'AFDA', fields: [
  {{ type: 'text', name: 'license_no', label: 'License' }},
  {{ type: 'secretInput', name: 'pin', label: 'PIN' }},
]}});
await rt.trust.pin(tcert.tcertId);
const issued = await rt.signing.issueSdoc({{ tcertId: tcert.tcertId, values: {{ license_no: 'AFDA-123', pin: 's3cret' }} }});
const pub = parseSignedObject(tcert.bytes).data.publicKey;
console.log(JSON.stringify({{ tcert: toBase64Url(tcert.bytes), sdoc: toBase64Url(issued.bytes), publicKey: pub }}));
"""
    result = subprocess.run(
        ["node", "--input-type=module", "-e", script],
        capture_output=True,
        text=True,
        cwd=str(JS_CORE_DIR),
    )
    assert result.returncode == 0, f"node producer failed: {result.stderr}"
    produced = json.loads(result.stdout)

    from qrs.envelope import parse_signed_object, verify_parsed_signed_object
    from qrs.crypto.registry import create_default_crypto_registry
    from qrs.id import from_base64url
    from qrs.cbor import cbor_encode

    # TCert self-signature must verify in Python.
    tcert_bytes = from_base64url(produced["tcert"])
    tcert_parsed = parse_signed_object(tcert_bytes)
    registry = create_default_crypto_registry()
    provider = registry.get(tcert_parsed.algorithm)
    assert verify_parsed_signed_object(tcert_parsed, provider, tcert_parsed.data["publicKey"]) is True

    # SDoc signature must verify in Python (with the secret AAD).
    sdoc_bytes = from_base64url(produced["sdoc"])
    sdoc_parsed = parse_signed_object(sdoc_bytes)
    aad = cbor_encode({"pin": "s3cret"})
    assert verify_parsed_signed_object(sdoc_parsed, provider, produced["publicKey"], aad) is True