def test_transfer_vectors_match(golden):
    assert encode_transfer_payload("sdoc", "aGVsbG8") == golden["transfer"]["payload"]
    assert encode_bundle(
        [{"type": "tcert", "bytes_b64": "dGNlcnQ"}, {"type": "sdoc", "bytes_b64": "c2RvYw"}]
    ) == golden["transfer"]["bundle"]
    assert to_hex(encode_qrs_file("tcert", "dGNlcnQ")) == golden["transfer"]["qrsFile"]
    assert to_hex(encode_qrs_bundle_file([{"type": "statement", "bytes_b64": "c3RhdGU"}])) == golden[
        "transfer"
    ]["qrsBundleFile"]


def test_transfer_decode_roundtrip():
    payload = encode_transfer_payload("sdoc", "aGVsbG8")
    decoded = decode_transfer_payload(payload)
    assert decoded is not None
    assert decoded.type == "sdoc"
    assert decoded.bytes_b64 == "aGVsbG8"

    bundle = encode_bundle([{"type": "tcert", "bytes_b64": "dGNlcnQ"}])
    decoded_bundle = decode_bundle(bundle)
    assert decoded_bundle is not None
    assert decoded_bundle.objects[0].type == "tcert"
    assert decoded_bundle.objects[0].bytes_b64 == "dGNlcnQ"

    qrs = decode_qrs_file(encode_qrs_file("tcert", "dGNlcnQ").decode("utf-8"))
    assert qrs is not None
    assert qrs["kind"] == "object"
    assert qrs["payload"].type == "tcert"


def test_transfer_rejects_foreign_payloads():
    assert decode_transfer_payload("https://example.com/x") is None
    assert decode_transfer_payload("qrs://v1/unknown/aGVsbG8") is None
    assert decode_bundle("qrs://v1/bundle/not-base64") is None
    assert decode_qrs_file("") is None


